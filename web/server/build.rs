//! Embed the operator web assets into the `xdesign` executable.
//!
//! The released product is the single `xdesign` binary. Shipping the web UI
//! therefore cannot depend on a Node.js toolchain, a separate static server, or
//! a filesystem copy of `web/`: every file under `web/assets/` is embedded at
//! compile time and served from memory by `xdesign web`.
//!
//! New or changed asset files are picked up automatically and trigger a
//! rebuild, so frontend work never has to edit a checked-in asset manifest.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn content_type(relative: &str) -> &'static str {
    match Path::new(relative)
        .extension()
        .and_then(|extension| extension.to_str())
        .unwrap_or_default()
        .to_ascii_lowercase()
        .as_str()
    {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "txt" | "md" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

fn collect(root: &Path, current: &Path, files: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(current) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, files);
        } else if path.is_file() {
            if let Ok(relative) = path.strip_prefix(root) {
                files.push(relative.to_string_lossy().replace('\\', "/"));
            }
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest directory"));
    let assets = manifest.join("web/assets");
    println!("cargo:rerun-if-changed=web/assets");

    let mut files = Vec::new();
    collect(&assets, &assets, &mut files);
    files.sort();

    let mut generated = String::from(
        "// Generated by web/server/build.rs; do not edit by hand.\n\
         pub static ASSET_FILES: &[(&str, &[u8], &str)] = &[\n",
    );
    for relative in &files {
        let path = assets.join(relative);
        println!("cargo:rerun-if-changed={}", path.display());
        generated.push_str(&format!(
            "    ({:?}, include_bytes!({:?}), {:?}),\n",
            format!("/{relative}"),
            path.to_string_lossy(),
            content_type(relative)
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").expect("out directory")).join("embedded_assets.rs");
    fs::write(out, generated).expect("write embedded asset table");
}
